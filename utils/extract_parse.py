import re
from typing import List, Optional, Tuple

def extract_boxed_content(text: str) -> Optional[str]:
    """Extract content from \\boxed{...} handling nested braces properly."""
    start_pattern = r'\\boxed\{'
    match = re.search(start_pattern, text)
    if not match:
        return None

    start_idx = match.end()
    brace_count = 1
    i = start_idx

    while i < len(text) and brace_count > 0:
        is_escaped = False
        if i > 0 and text[i-1] == '\\':
            num_backslashes = 0
            j = i - 1
            while j >= 0 and text[j] == '\\':
                num_backslashes += 1
                j -= 1
            is_escaped = (num_backslashes % 2 == 1)

        if not is_escaped:
            if text[i] == '{':
                brace_count += 1
            elif text[i] == '}':
                brace_count -= 1
        i += 1

    if brace_count == 0:
        content = text[start_idx:i-1]
        return content.strip()

    return None

def extract_boxed_answer(response_text: str, dataset_type: str = "math") -> Optional[str]:
    """Extract answer from \\boxed{} notation or other patterns."""
    if dataset_type in ["mmlu", "lab-bench", "vstar", "cvbench", "mmstar"]:
        for text in (response_text, response_text.replace("*", "")):
            matches = re.findall(r'(?:Final\s+)?Answer:\s*\(?([A-J])\)?', text, re.IGNORECASE)
            if matches:
                return matches[-1].upper()

            match = re.search(r'\b([A-J])\b\s*$', text.strip(), re.IGNORECASE)
            if match:
                return match.group(1).upper()

            matches = re.findall(r'(?:answer is|choose|option)\s+([A-J])\b', text, re.IGNORECASE)
            if matches:
                return matches[-1].upper()

        return None
    elif dataset_type == "stem":
        match = re.search(r'Final Answer:\s*(.+)', response_text, re.IGNORECASE | re.DOTALL)
        if match:
            answer = match.group(1).strip()
            return answer
        return response_text.strip()
    else:
        boxed_content = extract_boxed_content(response_text)
        if boxed_content:
            return boxed_content

        match = re.search(r'Final Answer:\s*(.+?)(?:\n|$)', response_text, re.IGNORECASE)
        if match:
            answer = match.group(1).strip()
            boxed_content = extract_boxed_content(answer)
            if boxed_content:
                return boxed_content
            return answer

        match = re.search(r'\*\*Answer:\*\*\s*(.+?)(?:\n\n|\Z)', response_text, re.DOTALL | re.IGNORECASE)
        if match:
            return match.group(1).strip()

        return None

def parse_sub_questions(text: str) -> List[str]:
    """Parse sub-questions from generated text."""
    lines = text.strip().split('\n')
    sub_questions = []

    for line in lines:
        line = line.strip()
        match = re.match(r'SubQ\d+:\s*(.+)', line, re.IGNORECASE)
        if match:
            sub_questions.append(match.group(1).strip())

    return sub_questions

def parse_subqa_pairs(text: str) -> List[Tuple[str, str]]:
    """Parse SubQ-SubA pairs from response text generated by build_all_subqa_prompt.

    Expected format:
    SubQ1: question1
    SubA1: answer1
    (can be multi-line)

    SubQ2: question2
    SubA2: answer2
    (can be multi-line)
    ...

    Returns:
        List of (sub_question, sub_answer) tuples
    """
    subqa_pairs = []
    lines = text.strip().split('\n')

    current_subq = None
    current_subq_num = None
    current_suba_num = None
    suba_lines = []

    i = 0
    while i < len(lines):
        line = lines[i].strip()

        subq_match = re.match(r'SubQ(\d+):\s*(.+)', line, re.IGNORECASE)
        if subq_match:
            if current_subq is not None and current_suba_num is not None and suba_lines:
                complete_suba = '\n'.join(suba_lines).strip()
                if current_subq_num == current_suba_num:
                    subqa_pairs.append((current_subq, complete_suba))
                suba_lines = []
                current_suba_num = None

            current_subq_num = int(subq_match.group(1))
            current_subq = subq_match.group(2).strip()
            i += 1
            continue

        suba_match = re.match(r'SubA(\d+):\s*(.+)', line, re.IGNORECASE)
        if suba_match:
            if current_subq is not None and current_suba_num is not None and suba_lines:
                complete_suba = '\n'.join(suba_lines).strip()
                if current_subq_num == current_suba_num:
                    subqa_pairs.append((current_subq, complete_suba))
                suba_lines = []
                current_subq = None
                current_subq_num = None

            current_suba_num = int(suba_match.group(1))
            first_line = suba_match.group(2).strip()
            suba_lines = [first_line] if first_line else []
            i += 1
            continue

        if current_suba_num is not None:
            if re.match(r'(Final Answer|SubQ\d+|SubA\d+):', line, re.IGNORECASE):
                pass
            else:
                suba_lines.append(line)

        i += 1

    if current_subq is not None and current_suba_num is not None and suba_lines:
        complete_suba = '\n'.join(suba_lines).strip()
        if current_subq_num == current_suba_num:
            subqa_pairs.append((current_subq, complete_suba))

    return subqa_pairs

def parse_batch_verification_response(response: str, num_subqas: int) -> Tuple[List[bool], str]:
    """Parse a batch verification response with multiple SubQ verdicts.

    Expected format:
        REASONING:
        ...

        VERDICTS:
        SubQ 1: true
        SubQ 2: false
        SubQ 3: true
        ...

    Args:
        response: The verification response text
        num_subqas: Expected number of SubQ-SubA pairs

    Returns:
        (list of verdicts, reasoning text) where verdicts[i] is True if SubQ i+1 is verified
    """
    lines = response.strip().split('\n')
    verdicts = [False] * num_subqas
    verdicts_started = False

    for line in lines:
        line_stripped = line.strip().lower()

        if 'verdict' in line_stripped and 's' in line_stripped:
            if 'subq' not in line_stripped and 'sub' not in line_stripped.replace('verdict', ''):
                verdicts_started = True
                continue

        if verdicts_started and 'subq' in line_stripped:
            try:
                parts = line_stripped.split(':')
                if len(parts) >= 2:
                    subq_part = parts[0].strip()
                    verdict_part = parts[1].strip()

                    match = re.search(r'(\d+)', subq_part)
                    if match:
                        subq_idx = int(match.group(1)) - 1

                        if 0 <= subq_idx < num_subqas:
                            if 'true' in verdict_part and 'false' not in verdict_part:
                                verdicts[subq_idx] = True
                            elif 'false' in verdict_part:
                                verdicts[subq_idx] = False
            except Exception:
                continue

    return verdicts, response
